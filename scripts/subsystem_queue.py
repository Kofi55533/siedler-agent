#!/usr/bin/env python3
"""subsystem_queue.py <siedler-sim-rs>/docs/subsystems/subsystems.json -> scripts/subsystems.json (the refill queue).

The whole-game subsystem map lives in the private siedler-sim-rs (docs/subsystems/, generated by tools/subsystem_map/);
this public queue keeps only what refill/opencode need: id, order, title, branch, scope, classes, files, fixtures, counts.
Hand-written scope/classes/files/fixtures of ids already in the queue are kept; status 'done' is kept.
Re-run after regenerating the map:  python3 scripts/subsystem_queue.py /path/to/siedler-sim-rs/docs/subsystems/subsystems.json
"""
import collections, json, os, sys

D = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(D, "subsystems.json")
GATE = "bc-full wintersturm economy wsecon build production combat combat-waves combat-big combat-long ai-long late-ai late-economy camp-crawford map-winterisland wintersturm-mapstart economy-mapstart".split()

m = json.load(open(sys.argv[1]))
old = json.load(open(OUT)) if os.path.exists(OUT) else {}
prev = {s["id"]: s for s in old.get("subsystems", [])}
subs = []
for s in m["subsystems"]:
    fx = collections.Counter()
    for f in s["functions"]:
        for x in f["executed"]:
            x = "bc-full" if x == "bc-300" else x
            if x in GATE:
                fx[x] += 1
    p = prev.get(s["id"], {})
    lo, hi = s["range"]
    e = {
        "id": s["id"], "order": s["order"], "status": p.get("status", "active"), "title": p.get("title", s["title"]),
        "branch": f"agent/subsystem-{s['id']}",
        "scope": p.get("scope") or (f"the {s['title']} subsystem: all {s['functions_total']} functions of the map entry '{s['id']}' "
                                     f"(addresses {lo}-{hi}, list in docs/subsystems/subsystems.json)"),
        "classes": p.get("classes") or ", ".join(c for c, _ in s["classes"][:8]),
        "files": p.get("files") or "crates/s5clean/src (choose the module from docs/subsystems/<id>.md; create one if none fits)",
        "fixtures": p.get("fixtures") or (" ".join(x for x, _ in fx.most_common(4)) or "bc-full"),
        "functions_total": s["functions_total"], "ported": s["ported"], "executed": s["executed"],
        "executed_unported": s["executed_unported"], "depends_on": [d for d, _ in s["depends_on"][:6]],
    }
    subs.append(e)
cfg = {"_doc": "refill queue of 'Subsystem:' runs, generated by scripts/subsystem_queue.py from siedler-sim-rs "
               "docs/subsystems/subsystems.json (whole-game map); refill keeps SUBSYSTEM_SLOTS (default 'slots') of them "
               "active in 'order', one run per subsystem; a subsystem is done when status is 'done' or its "
               "docs/subsystems/<id>.md on clean/integration says 'Status: complete'.",
       "slots": old.get("slots", 8) if old.get("slots", 2) != 2 else 8, "map_meta": m["meta"], "subsystems": subs}
json.dump(cfg, open(OUT, "w"), indent=1, ensure_ascii=False)
open(OUT, "a").write("\n")
print(f"{len(subs)} subsystems -> {OUT}")
